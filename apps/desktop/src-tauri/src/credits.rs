//! Settings › Source control › Remove agent credits when merging (item 75): the merge or squash message the app proposes, with the
//! lines that credit an AI agent taken out and every human co-author kept. Only the message of the merge the app is about to make
//! is changed, and only when the person turned the switch on: commits that already exist are never rewritten, so a rebase (which
//! makes no message) and a merge commit's own parents keep theirs.
//!
//! Lifted from T3 Code (pingdotgg/t3code at `8f5fd28`, MIT License, Copyright (c) T3 Tools Inc.):
//! `packages/source-control-core/src/server/mergeMessage.ts` (`removeAgentCredits`) and its tests, ported to Rust line for line.
//! The recognised list is fixed in code, in `src/lib/agentCredits.json`, which the page shows as it is:
//!
//! - a `Co-authored-by:` line (any case, a list's `-` or `*` before it allowed) whose address is one of `emails`; GitHub's
//!   `noreply@github.com`, which people use too, only with the name Copilot or GitHub Copilot;
//! - a line that is only "Generated with" or "Generated by" an agent of `agents`, with or without a robot before it and a full stop
//!   after, where a markdown link to one of `linkHosts` counts as its words.
//!
//! A line in a fenced code block or indented as code is an example and stays. When nothing is taken out the message is returned as
//! it was; otherwise the blank lines left at its end go, and line ends stay as they were (`\r\n` when the message had one).

use std::sync::OnceLock;

use regex::{Regex, RegexBuilder};
use serde_json::Value;

/// The list the page shows and this file reads.
const LIST: &str = include_str!("../../src/lib/agentCredits.json");

struct Rules {
    emails: Vec<String>,
    noreply_names: Vec<String>,
    generated: Regex,
    link: Regex,
    co_author: Regex,
    fence: Regex,
    bullet: Regex,
}

fn rules() -> &'static Rules {
    static R: OnceLock<Rules> = OnceLock::new();
    R.get_or_init(|| {
        let v: Value = serde_json::from_str(LIST).expect("agentCredits.json");
        let list = |k: &str| -> Vec<String> { v[k].as_array().expect("agentCredits.json list").iter().map(|x| x.as_str().expect("agentCredits.json word").to_string()).collect() };
        let alt = |words: Vec<String>| words.iter().map(|w| regex::escape(&w.to_lowercase())).collect::<Vec<_>>().join("|");
        let ci = |p: &str| RegexBuilder::new(p).case_insensitive(true).build().expect("credit pattern");
        Rules {
            emails: list("emails").into_iter().map(|e| e.to_lowercase()).collect(),
            noreply_names: list("githubNoreplyNames").into_iter().map(|n| n.to_lowercase()).collect(),
            generated: ci(&format!(r"^(?:🤖\s*)?generated (?:with|by)\s+(?:{})[.!]?$", alt(list("agents")))),
            link: ci(&format!(r"\[([^\[\]\r\n]+)\]\(https://(?:{})(?:/[^\s)\[\]]*)?\)", alt(list("linkHosts")))),
            co_author: ci(r"^co-authored-by:"),
            fence: Regex::new(r"^ {0,3}(`{3,}|~{3,})(.*)$").expect("fence pattern"),
            bullet: Regex::new(r"^[-*]\s+").expect("bullet pattern"),
        }
    })
}

/// Whether `text` (a trimmed line) is a `Co-authored-by:` trailer for a recognised agent.
fn is_agent_author(r: &Rules, text: &str) -> bool {
    let Some(prefix) = r.co_author.find(text) else { return false };
    if !text.ends_with('>') {
        return false;
    }
    let Some(email_start) = text.rfind('<') else { return false };
    if email_start < prefix.end() {
        return false;
    }
    let email = text[email_start + 1..text.len() - 1].to_lowercase();
    if !r.emails.contains(&email) {
        return false;
    }
    // GitHub's generic noreply address is also used by people: only Copilot's name makes it an agent's
    email != "noreply@github.com" || r.noreply_names.contains(&text[prefix.end()..email_start].trim().to_lowercase())
}

/// `message` with the recognised agent credit lines taken out, and how many were.
pub fn remove_agent_credits(message: &str) -> (String, u32) {
    let r = rules();
    let newline = if message.contains("\r\n") { "\r\n" } else { "\n" };
    let mut fence: Option<String> = None;
    let mut removed = 0u32;
    let mut kept: Vec<&str> = Vec::new();
    for line in message.split('\n').map(|l| l.strip_suffix('\r').unwrap_or(l)) {
        if line.starts_with("    ") || line.starts_with('\t') {
            kept.push(line);
            continue;
        }
        if let Some(c) = r.fence.captures(line) {
            let marker = c.get(1).map_or("", |m| m.as_str());
            let rest = c.get(2).map_or("", |m| m.as_str());
            match &fence {
                None => {
                    if marker.starts_with('~') || !rest.contains('`') {
                        fence = Some(marker.to_string());
                    }
                }
                Some(open) => {
                    if marker.as_bytes()[0] == open.as_bytes()[0] && marker.len() >= open.len() && rest.chars().all(|ch| ch == ' ' || ch == '\t') {
                        fence = None;
                    }
                }
            }
            kept.push(line);
            continue;
        }
        if fence.is_some() {
            kept.push(line);
            continue;
        }
        let trimmed = line.trim();
        let text = r.bullet.find(trimmed).map_or(trimmed, |m| &trimmed[m.end()..]);
        if !is_agent_author(r, text) {
            let footer = r.link.replace_all(text, "$1");
            if !r.generated.is_match(&footer) {
                kept.push(line);
                continue;
            }
        }
        removed += 1;
    }
    if removed == 0 {
        return (message.to_string(), 0);
    }
    while kept.len() > 1 && kept.last().is_some_and(|l| l.chars().all(|c| c == ' ' || c == '\t')) {
        kept.pop();
    }
    (kept.join(newline), removed)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn clean(m: &str) -> String {
        remove_agent_credits(m).0
    }

    // T3 Code's own cases (mergeMessage.test.ts), then Manut AI's.

    #[test]
    fn removes_recognized_agent_trailers_and_generated_footers_keeping_human_co_authors() {
        let m = [
            "Details about Claude support.",
            "",
            "",
            "Co-authored-by: Alice <alice@example.com>",
            "Co-authored-by: Claude <noreply@anthropic.com>",
            "* Co-authored-by: Codex <noreply@openai.com>",
            "co-authored-by: Cursor <cursoragent@cursor.com>",
            "Co-authored-by: Copilot <copilot@github.com>",
            "Co-Authored-By:\tGitHub Copilot   <NOREPLY@GITHUB.COM>",
            "",
            "🤖 Generated with [Claude Code](https://claude.ai/code)",
        ]
        .join("\n");
        assert_eq!(remove_agent_credits(&m), ("Details about Claude support.\n\n\nCo-authored-by: Alice <alice@example.com>".to_string(), 6));
    }

    #[test]
    fn removes_the_footer_claude_code_writes_today_which_links_to_claude_com() {
        let m = ["Details", "", "🤖 Generated with [Claude Code](https://claude.com/claude-code)", "", "Co-Authored-By: Claude <noreply@anthropic.com>"].join("\n");
        assert_eq!(clean(&m), "Details");
    }

    #[test]
    fn preserves_unknown_identities_humans_named_after_agents_and_ordinary_prose() {
        let m = [
            "Co-authored-by: Claude <claude@example.com>",
            "Co-authored-by: Alice <noreply@github.com>",
            "Co-authored-by: Release Bot <release@example.com>",
            "Generated by our new Claude integration.",
            "Generated with [Claude Code](https://example.com)",
            "",
        ]
        .join("\n");
        assert_eq!(remove_agent_credits(&m), (m.clone(), 0));
    }

    #[test]
    fn preserves_code_fences_and_block_quotes_containing_attribution_examples() {
        let ex = "Co-authored-by: Claude <noreply@anthropic.com>";
        let m = format!("Example:\n\n```text\n{ex}\n```\n\n> {ex}\n\n{ex}");
        assert_eq!(clean(&m), format!("Example:\n\n```text\n{ex}\n```\n\n> {ex}"));
    }

    #[test]
    fn removes_trailers_after_a_line_that_cannot_open_a_fence() {
        for line in ["``` text ```", "    ```", "\t~~~"] {
            assert_eq!(clean(&format!("{line}\n\nCo-authored-by: Claude <noreply@anthropic.com>")), line, "{line:?}");
        }
    }

    #[test]
    fn keeps_examples_after_a_false_closing_fence() {
        let ex = "Co-authored-by: Claude <noreply@anthropic.com>";
        for fence in ["```", "~~~"] {
            let two = &fence[..2];
            let first = &fence[..1];
            let content = format!("{fence}text\n{fence} trailing text\n{ex}\n    {fence}\n{ex}\n{two}\n{ex}\n   {fence}{first} \t");
            assert_eq!(clean(&format!("{content}\n\n{ex}")), content, "{fence}");
        }
    }

    #[test]
    fn preserves_crlf_line_endings() {
        let m = "Details\r\n\r\nCo-authored-by: Claude <noreply@anthropic.com>\r\nCo-authored-by: Alice <alice@example.com>";
        assert_eq!(clean(m), "Details\r\n\r\nCo-authored-by: Alice <alice@example.com>");
    }

    #[test]
    fn returns_an_empty_body_when_only_agent_credits_remain() {
        assert_eq!(clean("Co-authored-by: Claude <noreply@anthropic.com>\n\nGenerated by Codex\n"), "");
    }

    #[test]
    fn every_human_co_author_survives_and_a_message_without_credits_is_returned_as_it_was() {
        let m = "* Draw the QR\n\nCo-authored-by: Ana <ana@shop.co>\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>\nCo-authored-by: Somchai <somchai@users.noreply.github.com>\n\n* Read the amount";
        let (out, n) = remove_agent_credits(m);
        assert_eq!(n, 1);
        assert_eq!(out, "* Draw the QR\n\nCo-authored-by: Ana <ana@shop.co>\nCo-authored-by: Somchai <somchai@users.noreply.github.com>\n\n* Read the amount");
        for human in ["Co-authored-by: Ana <ana@shop.co>", "Co-authored-by: Somchai <somchai@users.noreply.github.com>"] {
            assert!(out.contains(human), "{human}");
        }
        let plain = "Merge pull request #7 from mygogocash/kit/qr\n\nAdd the PromptPay QR   \n\n";
        assert_eq!(remove_agent_credits(plain), (plain.to_string(), 0));
    }

    #[test]
    fn the_list_is_the_one_the_page_shows() {
        let v: Value = serde_json::from_str(LIST).unwrap();
        assert!(v["emails"].as_array().unwrap().iter().any(|e| e == "noreply@anthropic.com"));
        assert!(v["agents"].as_array().unwrap().iter().any(|e| e == "Claude Code"));
        assert!(rules().generated.is_match("generated with claude code."));
        assert!(!rules().generated.is_match("generated with care"));
    }
}
